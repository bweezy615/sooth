def test_every_rendered_email_carries_an_unsubscribe():
    new = [div("g1", 3.0)]
    unsub = alert_token.unsub_link("a@b.com", "https://sooth.bet", SECRET)
    prefs = alert_token.prefs_link("a@b.com", "https://sooth.bet", SECRET)
    _, html, text = render(new, unsub, prefs)
    for body in (html, text):
        assert "unsub=" in body
        assert "1-800-522-4700" in body


def test_the_sender_refuses_to_mail_without_a_working_opt_out():
    from engine import mailer
    assert mailer.send("k", "a@b.com", "s", "<p>x</p>", "x", "") is False


def test_signing_without_a_secret_raises_rather_than_minting_a_dead_link(monkeypatch):
    monkeypatch.delenv("AUTH_SECRET", raising=False)
    with pytest.raises(alert_token.NoSecret):
        alert_token.unsub_link("a@b.com")


def test_tokens_round_trip_and_reject_tampering():
    tok = alert_token.sign({"t": "u", "e": "a@b.com", "exp": 4102444800000}, SECRET)
    assert alert_token.verify(tok, SECRET)["e"] == "a@b.com"
    assert alert_token.verify(tok[:-2] + "zz", SECRET) is None
    assert alert_token.verify("garbage", SECRET) is None
    assert alert_token.verify("", SECRET) is None
    expired = alert_token.sign({"t": "u", "e": "a@b.com", "exp": 1}, SECRET)
    assert alert_token.verify(expired, SECRET) is None
    assert alert_token.verify(tok, "a-different-secret") is None


# Generated by api/_auth.js under AUTH_SECRET="selfcheck-secret". If this ever
# fails, the two halves of the link scheme have drifted and every unsubscribe
# link already sitting in someone's mailbox has stopped working.
NODE_VECTOR = (
    "eyJ0IjoidSIsImUiOiJhQGIuY29tIiwiZXhwIjo0MTAyNDQ0ODAwMDAwfQ"
    ".2nI7J2WSlZkoI6H5PjNogX1SlPbl0kEibj7Uetjpep0"
)


def test_python_matches_the_node_signature_byte_for_byte():
    assert alert_token.sign(
        {"t": "u", "e": "a@b.com", "exp": 4102444800000}, SECRET) == NODE_VECTOR
    assert alert_token.verify(NODE_VECTOR, SECRET) == {
        "t": "u", "e": "a@b.com", "exp": 4102444800000}


def test_node_verifies_a_link_python_just_minted():
    """The check that actually matters, run against the real Node module."""
    tok = alert_token.sign({"t": "u", "e": "live@x.com", "exp": 4102444800000},
                           SECRET)
    root = Path(__file__).resolve().parents[1]
    script = (
        'process.env.AUTH_SECRET=%s;'
        'const a=require(%s);'
        'const p=a.verify(%s);'
        'process.stdout.write(JSON.stringify(p));'
        % (json.dumps(SECRET), json.dumps(str(root / "api" / "_auth.js")),
           json.dumps(tok))
    )
    try:
        out = subprocess.run(["node", "-e", script], capture_output=True,
                             text=True, timeout=30, check=True).stdout
    except (FileNotFoundError, subprocess.SubprocessError) as e:
        pytest.skip(f"node unavailable: {e}")
    assert json.loads(out) == {"t": "u", "e": "live@x.com", "exp": 4102444800000}


# ---------------------------------------------------------------------------
# The watchlist format has two implementations — engine/subscribers.py writes
# and reads it, api/alerts.js writes it from the browser — and they must agree
# forever. A drift here does not throw: it silently drops teams from somebody's
# list, and the only symptom is an email that never arrives.

TEAM_VECTORS = [
    "nba:NYK,nfl:BUF",
    "nba:nyk,NFL:buf",          # case is repaired, not rejected
    "nba:NYK,nba:NYK",          # deduped
    "NYK",                      # unscoped: which league's NYK?
    "nba:",                     # no team named
    "nba:TOOLONG",              # not an abbreviation
    "basketball:NYK",           # sport too long
    "nba:N Y",                  # spaces are not abbreviations
    " nfl:BUF , nba:NYK ",      # whitespace around entries
    "",
    ",,,",
    "nba:NYK,junk,nfl:BUF",     # one bad entry does not poison the rest
    ",".join(f"nba:T{100 + i}" for i in range(90)),   # past Stripe's 500 cap
]


def test_python_and_node_agree_on_the_watchlist_format():
    root = Path(__file__).resolve().parents[1]
    script = (
        'const V=require(%s)._internals;'
        'process.stdout.write(JSON.stringify('
        '  %s.map(s => V.cleanTeams(s).join(","))));'
        % (json.dumps(str(root / "api" / "alerts.js")), json.dumps(TEAM_VECTORS))
    )
    try:
        out = subprocess.run(["node", "-e", script], capture_output=True,
                             text=True, timeout=30, check=True).stdout
    except (FileNotFoundError, subprocess.SubprocessError) as e:
        pytest.skip(f"node unavailable: {e}")
    node = json.loads(out)
    py = [subscribers.serialise_teams(subscribers.parse_teams(v))
          for v in TEAM_VECTORS]
    assert node == py


def test_a_watchlist_never_exceeds_the_stripe_metadata_cap():
    big = [f"nba:T{100 + i}" for i in range(200)]
    stored = subscribers.serialise_teams(big)
    assert len(stored) <= subscribers.TEAMS_MAX_BYTES
    # truncation is from the SORTED list, so the same watchlist always stores
    # the same subset rather than a new arbitrary one on every write
    kept = stored.split(",")
    assert kept == sorted(big)[:len(kept)]
    assert subscribers.parse_teams(stored) == frozenset(kept)


def test_game_alerts_need_somebody_to_follow():
    s = subscribers.Subscriber("a@b.com", frozenset({"game"}), 2.5, frozenset())
    assert not s.wants("game"), "an empty watchlist matches nothing, not everything"
    assert not s.watches("nba:NYK")
    t = subscribers.Subscriber("a@b.com", frozenset({"game"}), 2.5,
                               frozenset({"nba:NYK"}))
    assert t.wants("game") and t.watches("nfl:BUF", "nba:NYK")
    assert not t.watches("nfl:BUF"), "only the teams they actually picked"
